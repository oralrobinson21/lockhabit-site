CREATE OR REPLACE FUNCTION public.record_stripe_checkout_event(
  p_event_id text,
  p_event_type text,
  p_checkout_session_id text,
  p_outcome text
)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $$
BEGIN
  INSERT INTO public.stripe_webhook_events (
    event_id, event_type, checkout_session_id, outcome
  ) VALUES (
    p_event_id, p_event_type, p_checkout_session_id, p_outcome
  )
  ON CONFLICT (event_id) DO UPDATE
  SET outcome = EXCLUDED.outcome,
      updated_at = now();
END;
$$;

CREATE OR REPLACE FUNCTION public.record_paid_checkout(
  p_event_id text,
  p_event_type text,
  p_checkout_session_id text,
  p_payment_intent_id text,
  p_customer_email text,
  p_customer_name text,
  p_currency text,
  p_amount_subtotal integer,
  p_amount_shipping integer,
  p_amount_tax integer,
  p_amount_total integer,
  p_shipping_details jsonb,
  p_items jsonb
)
RETURNS TABLE(order_id uuid, order_number bigint)
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_order public.orders%ROWTYPE;
BEGIN
  INSERT INTO public.stripe_webhook_events (
    event_id, event_type, checkout_session_id, outcome
  ) VALUES (
    p_event_id, p_event_type, p_checkout_session_id, 'paid_recorded'
  )
  ON CONFLICT (event_id) DO UPDATE
  SET outcome = 'paid_recorded',
      updated_at = now();

  INSERT INTO public.orders (
    checkout_session_id,
    payment_intent_id,
    stripe_event_id,
    customer_email,
    customer_name,
    amount_subtotal,
    amount_shipping,
    amount_tax,
    amount_total,
    currency,
    payment_status,
    shipping_details,
    items
  ) VALUES (
    p_checkout_session_id,
    p_payment_intent_id,
    p_event_id,
    p_customer_email,
    p_customer_name,
    p_amount_subtotal,
    p_amount_shipping,
    p_amount_tax,
    p_amount_total,
    p_currency,
    'paid',
    p_shipping_details,
    p_items
  )
  ON CONFLICT (checkout_session_id) DO UPDATE
  SET payment_intent_id = COALESCE(public.orders.payment_intent_id, EXCLUDED.payment_intent_id),
      stripe_event_id = EXCLUDED.stripe_event_id,
      customer_email = EXCLUDED.customer_email,
      customer_name = EXCLUDED.customer_name,
      amount_subtotal = EXCLUDED.amount_subtotal,
      amount_shipping = EXCLUDED.amount_shipping,
      amount_tax = EXCLUDED.amount_tax,
      amount_total = EXCLUDED.amount_total,
      currency = EXCLUDED.currency,
      payment_status = 'paid',
      shipping_details = EXCLUDED.shipping_details,
      items = EXCLUDED.items,
      updated_at = now()
  RETURNING * INTO v_order;

  INSERT INTO public.order_confirmation_deliveries (
    checkout_session_id, order_id
  ) VALUES (
    v_order.checkout_session_id, v_order.id
  )
  ON CONFLICT (checkout_session_id) DO NOTHING;

  RETURN QUERY SELECT v_order.id, v_order.order_number;
END;
$$;

CREATE OR REPLACE FUNCTION public.claim_order_confirmation(p_checkout_session_id text)
RETURNS TABLE(order_id uuid)
LANGUAGE sql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $$
  UPDATE public.order_confirmation_deliveries
  SET status = 'sending',
      attempts = attempts + 1,
      claimed_at = now(),
      updated_at = now()
  WHERE checkout_session_id = p_checkout_session_id
    AND (
      status IN ('pending', 'failed')
      OR (status = 'sending' AND claimed_at < now() - interval '10 minutes')
    )
  RETURNING order_id;
$$;

