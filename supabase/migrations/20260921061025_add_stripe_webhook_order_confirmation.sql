ALTER TABLE public.orders
  ADD COLUMN order_number bigint GENERATED BY DEFAULT AS IDENTITY,
  ADD COLUMN stripe_event_id text,
  ADD COLUMN customer_name text,
  ADD COLUMN amount_subtotal integer NOT NULL DEFAULT 0,
  ADD COLUMN amount_shipping integer NOT NULL DEFAULT 0,
  ADD COLUMN amount_tax integer NOT NULL DEFAULT 0,
  ADD COLUMN confirmation_sent_at timestamptz;

CREATE UNIQUE INDEX orders_order_number_key ON public.orders (order_number);
CREATE UNIQUE INDEX orders_payment_intent_id_key
  ON public.orders (payment_intent_id)
  WHERE payment_intent_id IS NOT NULL;

CREATE TABLE public.stripe_webhook_events (
  event_id text PRIMARY KEY,
  event_type text NOT NULL,
  checkout_session_id text NOT NULL,
  outcome text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.order_confirmation_deliveries (
  checkout_session_id text PRIMARY KEY REFERENCES public.orders(checkout_session_id) ON DELETE CASCADE,
  order_id uuid NOT NULL UNIQUE REFERENCES public.orders(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'sending', 'sent', 'failed')),
  attempts integer NOT NULL DEFAULT 0,
  claimed_at timestamptz,
  sent_at timestamptz,
  provider_message_id text,
  last_error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.stripe_webhook_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_confirmation_deliveries ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.orders FROM anon, authenticated;
REVOKE ALL ON public.stripe_webhook_events FROM anon, authenticated;
REVOKE ALL ON public.order_confirmation_deliveries FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON public.stripe_webhook_events TO service_role;
GRANT SELECT, INSERT, UPDATE ON public.order_confirmation_deliveries TO service_role;

CREATE POLICY "Store service manages Stripe webhook events"
ON public.stripe_webhook_events
FOR ALL TO service_role
USING (true)
WITH CHECK (true);

CREATE POLICY "Store service manages order confirmation deliveries"
ON public.order_confirmation_deliveries
FOR ALL TO service_role
USING (true)
WITH CHECK (true);

